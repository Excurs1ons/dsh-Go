package io.github.ccch1mneyyy.dsh_app.runtime

import java.io.File
import java.util.concurrent.TimeUnit

/**
 * Whether this phone can start the runtime as root, and whether the person authorized it.
 *
 * [detected] is a plain file check and stays cheap enough for every status emit. [probe]
 * runs `su`, which may show the root manager's authorization prompt, so only an explicit
 * user action calls it — never a start, never a status refresh.
 */
object RootLaunch {
    /** Where root managers install their `su`. */
    private val SU_PATHS = listOf(
        "/system/bin/su",
        "/system/xbin/su",
        "/sbin/su",
        "/su/bin/su",
        "/data/adb/ksu/bin/su",
        "/data/adb/ap/bin/su",
        "/debug_ramdisk/su",
    )

    /** A ready root launch: the generated script and the directory the guest is mounted on. */
    data class Plan(val script: File, val mount: File)

    /**
     * Turns the composed PRoot argv into the same command under `su` + chroot: binds become
     * real mounts and the expanded guest command keeps every argument. PRoot's own flags and
     * its `/proc`/`/dev`/`/sys` binds are dropped — the script mounts those natively.
     *
     * Returns null when the argv has no `/usr/bin/env` to split on.
     */
    fun plan(rootfs: File, filesDir: File, argv: List<String>): Plan? {
        val envAt = argv.indexOf("/usr/bin/env")
        if (envAt <= 0) return null
        val binds = ArrayList<String>()
        var index = 0
        while (index < envAt) {
            val arg = argv[index++]
            if (arg == "-b" || arg == "--bind") binds += argv.getOrNull(index++) ?: return null
            else if (arg.startsWith("--bind=")) binds += arg.substringAfter('=')
        }
        val runtime = File(filesDir, "runtime")
        val mount = File(runtime, "root-mnt")
        val upper = File(runtime, "root-upper")
        val work = File(runtime, "root-work")
        val script = File(runtime, "root-launch.sh")
        runtime.mkdirs()

        val guests = binds.mapNotNull { spec ->
            val parts = spec.split(':')
            val host = parts[0]
            val guest = parts.getOrElse(1) { host }
            when {
                guest == "/dev" || guest == "/proc" || guest == "/sys" -> null
                guest.startsWith("/dev/") || guest.startsWith("/proc/") -> null
                host == rootfs.absolutePath || host == rootfs.canonicalPath -> null
                else -> host to guest
            }
        }
        val text = buildString {
            appendLine("#!/system/bin/sh")
            appendLine("# Generated by DSH Go for root mode. Deleted when root mode stops being used.")
            appendLine("set -u")
            appendLine("MNT=${quote(mount.absolutePath)}")
            appendLine("UPPER=${quote(upper.absolutePath)}")
            appendLine("WORK=${quote(work.absolutePath)}")
            appendLine("case \"\${1:-boot}\" in")
            appendLine("  teardown)")
            for (guest in listOf("/dev/shm", "/sdcard", "/storage", "/system", "/apex", "/proc", "/sys", "/dev")) {
                appendLine("    umount -l \"\$MNT$guest\" 2>/dev/null")
            }
            appendLine("    umount -l \"\$MNT\" 2>/dev/null")
            appendLine("    exit 0 ;;")
            appendLine("esac")
            appendLine("mkdir -p \"\$MNT\" \"\$UPPER\" \"\$WORK\" || exit 89")
            appendLine("mount -t overlay overlay -o \"lowerdir=${rootfs.absolutePath},upperdir=\$UPPER,workdir=\$WORK\" \"\$MNT\" || exit 90")
            appendLine("mount --bind /dev \"\$MNT/dev\" || exit 91")
            appendLine("mount --bind /proc \"\$MNT/proc\" || exit 92")
            appendLine("mount --bind /sys \"\$MNT/sys\" || exit 93")
            appendLine("mount -t tmpfs tmpfs \"\$MNT/dev/shm\" 2>/dev/null")
            for ((host, guest) in guests) {
                appendLine("mkdir -p \"\$MNT$guest\" 2>/dev/null")
                appendLine("mount --bind ${quote(host)} \"\$MNT$guest\" 2>/dev/null")
            }
            appendLine("exec chroot \"\$MNT\" " + argv.drop(envAt).joinToString(" ") { quote(it) })
        }
        script.writeText(text)
        return Plan(script, mount)
    }

    /** Unmounts whatever [plan] mounted; safe to call when it never got that far. */
    fun teardown(script: File) {
        try {
            val process = ProcessBuilder("su", "-c", "sh ${quote(script.absolutePath)} teardown")
                .redirectErrorStream(true)
                .start()
            process.waitFor(TEARDOWN_TIMEOUT_MS, TimeUnit.MILLISECONDS)
        } catch (_: Exception) {
            // A missing su or a killed process leaves the mounts to the kernel at reboot.
        }
    }

    private fun quote(value: String): String = "'" + value.replace("'", "'\\''") + "'"

    /** Wire values are part of the status map; keep them stable. */
    enum class State(val wire: String) {
        UNKNOWN("unknown"),
        UNAVAILABLE("unavailable"),
        AUTHORIZED("authorized"),
        DENIED("denied"),
        TIMEOUT("timeout"),
    }

    data class Probe(val state: State, val detail: String? = null)

    /** Longer than any reasonable authorization dialog: the person has to read and tap. */
    private const val PROBE_TIMEOUT_MS = 30_000L
    private const val TEARDOWN_TIMEOUT_MS = 5_000L
    private const val MAX_DETAIL = 200

    /** A root manager is installed. Says nothing about whether it is authorized. */
    fun detected(): Boolean = SU_PATHS.any { File(it).exists() }

    /**
     * Asks the root manager for uid 0. Blocks until the person answers, the process exits,
     * or [PROBE_TIMEOUT_MS] passes; callers must not run it on the main thread.
     */
    fun probe(): Probe {
        if (!detected()) return Probe(State.UNAVAILABLE)
        val process = try {
            ProcessBuilder("su", "-c", "id -u").redirectErrorStream(true).start()
        } catch (error: Exception) {
            return Probe(State.DENIED, error.message?.take(MAX_DETAIL))
        }
        val output = StringBuilder()
        val reader = Thread {
            try {
                process.inputStream.bufferedReader().use { reader -> output.append(reader.readText()) }
            } catch (_: Exception) {
                // A destroyed process reports its own failure through the exit value below.
            }
        }.apply { isDaemon = true; start() }
        val finished = try {
            process.waitFor(PROBE_TIMEOUT_MS, TimeUnit.MILLISECONDS)
        } catch (_: InterruptedException) {
            Thread.currentThread().interrupt()
            false
        }
        if (!finished) {
            process.destroyForcibly()
            return Probe(State.TIMEOUT)
        }
        reader.join(500)
        val text = output.toString().trim()
        return if (process.exitValue() == 0 && text.lineSequence().any { it.trim() == "0" }) {
            Probe(State.AUTHORIZED, text.take(MAX_DETAIL))
        } else {
            Probe(State.DENIED, text.take(MAX_DETAIL).ifEmpty { null })
        }
    }
}
